"""Write the command-line reference (docs/cli/) from the tool manifest, and the list of
command functions in the API reference (docs/api/commands.md).

    python scripts/docs/cli_reference.py          # rewrite them
    python scripts/docs/cli_reference.py --check  # exit 1 if they are out of date

test/test_docs_commands.py runs the check, so the references can't drift from the code.
"""
import argparse
import sys
from pathlib import Path

from domainator.cli.manifest import manifest
from domainator.cli.registry import TOOLS

DOCS = Path(__file__).resolve().parents[2] / "docs"
OUT_DIR = DOCS / "cli"
API_COMMANDS = DOCS / "api" / "commands.md"


def _cell(text) -> str:
    """Help text as one table cell. Brackets are escaped so that text such as a PROSITE motif's
    ``[DE](2)`` doesn't render as a link."""
    text = str(text).replace("%%", "%").replace("|", "\\|").replace("[", "\\[").replace("]", "\\]")
    return text.replace("\n", " ").strip()


def _value(parameter) -> str:
    if parameter["kind"] == "flag":
        return ""
    if parameter["kind"] == "columns":
        return "columns..."
    if "choices" in parameter:
        value = "{" + ",".join(str(c) for c in parameter["choices"]) + "}"
    elif parameter["kind"] == "path":
        value = {"input": "FILE", "output": "FILE", "directory": "DIR", "program": "PROGRAM"}[parameter["role"]]
    else:
        value = parameter["type"].upper()
    if parameter.get("multiple"):
        value += " ..."
    elif "count" in parameter:
        value = " ".join([value] * parameter["count"])
    return value


def _default(parameter) -> str:
    if parameter.get("default_dynamic"):
        return "(depends on your environment)"
    if parameter["kind"] == "flag":
        return ""
    default = parameter.get("default")
    if default is None:
        return "required" if parameter.get("required") else ""
    if isinstance(default, list):
        return " ".join(str(d) for d in default)
    return str(default)


def tool_page(tool) -> str:
    lines = [f"[CLI reference](README.md)", f"# domainator {tool['name']}", "", tool["summary"], "",
             "```", tool["description"], "```", ""]
    if tool["required_outputs"]:
        outputs = ", ".join(f"`--{name}`" for name in tool["required_outputs"])
        lines += [f"Give at least one of these outputs: {outputs}. `-` as an input or output means standard "
                  "input or output, where the option says it is allowed.", ""]
    lines += ["| Option | Value | Default | Description |", "|---|---|---|---|"]
    columns = None
    for parameter in tool["parameters"]:
        flags = ", ".join(f"`{f}`" for f in parameter["flags"] + parameter.get("negative_flags", []))
        lines.append(f"| {flags} | {_cell(_value(parameter))} | {_cell(_default(parameter))} | {_cell(parameter['help'].split(' Columns:')[0])} |")
        if parameter["kind"] == "columns":
            columns = parameter["columns"]
    lines.append("")
    if columns:
        lines += ["## Columns", "", "| Column | Description |", "|---|---|"]
        for column in columns:
            token = ":".join([column["name"]] + column["args"]) + ("[:...]" if column["repeat_last"] else "")
            lines.append(f"| `{token}` | {_cell(column['help'])} |")
        lines.append("")
    lines += ["Every command also takes `--config FILE` (options from a JSON or YAML file, keyed by option name) "
              "and `--print_config`.", ""]
    return "\n".join(lines)


def index_page(described) -> str:
    lines = ["[index](../README.md)", "# Command-line reference", "",
             "Generated from the commands' parsers by `scripts/docs/cli_reference.py`. "
             "`domainator <command> --help` shows the same options.", ""]
    for category in described["categories"]:
        tools = [t for t in described["tools"] if t["category"] == category["name"]]
        if tools:
            lines += [f"## {category['title']}", ""]
            lines += [f"- [{t['name']}]({t['name']}.md): {t['summary']}" for t in tools]
            lines.append("")
    return "\n".join(lines)


def api_commands_page(described) -> str:
    lines = ["[API reference](index.md)", "# Command functions", "",
             "Each command is also a function: `from domainator.<command> import <command>`. Its main input is "
             "its only positional parameter; the others are keyword-only and named like the command's options. "
             "Generated by `scripts/docs/cli_reference.py`; the entries are rendered by mkdocstrings.", ""]
    for category in described["categories"]:
        tools = [t for t in described["tools"] if t["category"] == category["name"]]
        if tools:
            lines += [f"## {category['title']}", ""]
            for tool in tools:
                lines += [f"::: domainator.{TOOLS[tool['name']].module}.{tool['name']}", ""]
    return "\n".join(lines)


def pages():
    described = manifest()
    out = {"README.md": index_page(described)}
    out.update({f"{tool['name']}.md": tool_page(tool) for tool in described["tools"]})
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Only report whether docs/cli/ is up to date.")
    params = parser.parse_args(argv)
    wanted = pages()
    existing = {p.name for p in OUT_DIR.glob("*.md")} if OUT_DIR.exists() else set()
    stale = sorted(name for name, text in wanted.items() if not (OUT_DIR / name).exists() or (OUT_DIR / name).read_text() != text)
    extra = sorted(existing - set(wanted))
    api_commands = api_commands_page(manifest())
    api_stale = not API_COMMANDS.exists() or API_COMMANDS.read_text() != api_commands
    if params.check:
        if stale or extra or api_stale:
            names = stale + extra + (["../api/commands.md"] if api_stale else [])
            print(f"docs/cli/ is out of date ({', '.join(names)}); run python scripts/docs/cli_reference.py", file=sys.stderr)
            return 1
        return 0
    API_COMMANDS.parent.mkdir(parents=True, exist_ok=True)
    API_COMMANDS.write_text(api_commands)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (OUT_DIR / name).write_text(wanted[name])
    for name in extra:
        (OUT_DIR / name).unlink()
    return 0


if __name__ == "__main__":
    sys.exit(main())
