"""Domainator: protein domain and genome neighborhood analysis.

Every ``domainator <command>`` is also a library function, ``from domainator.<command> import
<command>``. This package exports the shared pieces: reading and writing sequence files,
matrices, the annotation feature types, and the exceptions. See docs/stability.md for what
the 1.x releases keep stable.
"""
__version__ = "1.0.0rc1"     # remember to update version in README.md also. And if you make breaking changes to the matrix file format, increment the matrix file version in data_matrix.py.
DOMAIN_FEATURE_NAME="Domainator" # Changing this will break backwards compatibility with files generated by other versions of Domainator
DOMAIN_SEARCH_BEST_HIT_NAME="Domain_Search" # Changing this will break backwards compatibility with files generated by other versions of Domainator

# Exported names, imported on first use so that `import domainator` stays cheap.
_LAZY_EXPORTS = {
    "parse_seqfiles": "domainator.seqio",
    "write_genbank": "domainator.seqio",
    "DataMatrix": "domainator.data_matrix",
    "DomainatorError": "domainator.errors",
    "InputError": "domainator.errors",
    "ExternalToolError": "domainator.errors",
    "OutputSizeLimitExceeded": "domainator.errors",
    "FormatVersionError": "domainator.errors",
}

__all__ = ["__version__", "DOMAIN_FEATURE_NAME", "DOMAIN_SEARCH_BEST_HIT_NAME", *_LAZY_EXPORTS]


def __getattr__(name):
    module = _LAZY_EXPORTS.get(name)
    if module is None:
        raise AttributeError(f"module 'domainator' has no attribute {name!r}")
    import importlib
    value = getattr(importlib.import_module(module), name)
    globals()[name] = value
    return value


def __dir__():
    return sorted(set(globals()) | set(_LAZY_EXPORTS))
