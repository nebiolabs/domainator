import pytest
import tempfile
import os
from io import BytesIO, StringIO
from pyhmmer import easel
from pyhmmer.plan7 import HMM
from domainator.hmmer_build import hmmer_build, main
from pathlib import Path


@pytest.fixture
def msa_content():
    return b">seq1\nACGTACGT\n>seq2\nACGTACGA\n"

def create_msa_file(content):
    with tempfile.NamedTemporaryFile(delete=False, mode="wb") as f:
        f.write(content)
        return f.name

@pytest.fixture
def msa_file(msa_content):
    file_path = create_msa_file(msa_content)
    yield file_path
    os.unlink(file_path)

def test_hmmer_build_with_required_params():
    msa_content = b">seq1\nACGTACGT\n>seq2\nACGTACGA\n"
    msa_file = create_msa_file(msa_content)

    with open(msa_file, "rb") as file:
        hmm = hmmer_build(file, name="test_profile")
        assert isinstance(hmm, HMM)
        assert hmm.name == "test_profile"

    os.unlink(msa_file)

def test_hmmer_build_with_optional_params():
    msa_content = b">seq1\nACGTACGT\n>seq2\nACGTACGA\n"
    msa_file = create_msa_file(msa_content)

    with open(msa_file, "rb") as file:
        hmm = hmmer_build(file, name="test_profile", acc="P12345", desc="Test profile description", alphabet=easel.Alphabet.dna())
        assert isinstance(hmm, HMM)
        assert hmm.name == "test_profile"
        assert hmm.accession == "P12345"
        assert hmm.description == "Test profile description"

    os.unlink(msa_file)

def test_hmmer_build_with_binaryio():
    msa_content = b">seq1\nACGTACGT\n>seq2\nACGTACGA\n"
    msa_file = BytesIO(msa_content)

    hmm = hmmer_build(msa_file, name="test_profile", acc="P12345", desc="Test profile description", alphabet=easel.Alphabet.dna())
    assert isinstance(hmm, HMM)
    assert hmm.name == "test_profile"
    assert hmm.accession == "P12345"
    assert hmm.description == "Test profile description"


def test_main_with_required_params(msa_file, capsys):
    main(["--name", "test_profile", "--input", msa_file, "-o", "-"])
    captured = capsys.readouterr()
    assert "HMMER3/f" in captured.out
    assert "NAME  test_profile" in captured.out

def test_main_with_optional_params(msa_file, capsys):
    main(["--name", "test_profile", "--acc", "P12345", "--desc", "Test profile description", "--input", msa_file, "--alphabet", "dna", "-o", "-"])
    captured = capsys.readouterr()
    output = captured.out
    assert "HMMER3/f" in output
    assert "NAME  test_profile" in output
    assert "ACC   P12345" in output
    assert "DESC  Test profile description" in output



# --- DNA / RNA alphabets --------------------------------------------------
#
# The .afa fixtures were generated by test/data/README_alphabet_fixtures.md;
# the .hmm fixtures were built from them with hmmer_build.py itself.

def _build(shared_datadir, args):
    with tempfile.TemporaryDirectory() as output_dir:
        out_path = os.path.join(output_dir, "out.hmm")
        main(args + ["-o", out_path])
        return Path(out_path).read_text()


def test_hmmer_build_dna_alphabet(shared_datadir):
    text = _build(shared_datadir, ["-i", str(shared_datadir / "dna_msa_1.afa"), "--name", "d", "--alphabet", "dna"])
    assert "ALPH  DNA" in text
    assert "MAXL  " in text


def test_hmmer_build_rna_alphabet(shared_datadir):
    text = _build(shared_datadir, ["-i", str(shared_datadir / "rna_msa_1.afa"), "--name", "r", "--alphabet", "rna"])
    assert "ALPH  RNA" in text


def test_hmmer_build_infers_dna_and_rna(shared_datadir):
    assert "ALPH  DNA" in _build(shared_datadir, ["-i", str(shared_datadir / "dna_msa_1.afa"), "--name", "d"])
    assert "ALPH  RNA" in _build(shared_datadir, ["-i", str(shared_datadir / "rna_msa_1.afa"), "--name", "r"])


def test_hmmer_build_window_length_sets_maxl(shared_datadir):
    default_text = _build(shared_datadir, ["-i", str(shared_datadir / "dna_msa_1.afa"), "--name", "d", "--alphabet", "dna"])
    forced_text = _build(shared_datadir, ["-i", str(shared_datadir / "dna_msa_1.afa"), "--name", "d", "--alphabet", "dna", "--window_length", "500"])
    assert "MAXL  500" not in default_text
    assert "MAXL  500" in forced_text


def test_hmmer_build_window_beta_changes_maxl(shared_datadir):
    default_text = _build(shared_datadir, ["-i", str(shared_datadir / "dna_msa_1.afa"), "--name", "d", "--alphabet", "dna"])
    beta_text = _build(shared_datadir, ["-i", str(shared_datadir / "dna_msa_1.afa"), "--name", "d", "--alphabet", "dna", "--window_beta", "1e-3"])
    default_maxl = [l for l in default_text.splitlines() if l.startswith("MAXL")][0]
    beta_maxl = [l for l in beta_text.splitlines() if l.startswith("MAXL")][0]
    assert default_maxl != beta_maxl


def test_hmmer_build_window_length_rejected_for_amino():
    # pyhmmer silently accepts window_length for an amino alphabet, so nothing but this
    # check stands between the user and a meaningless setting.
    msa_file = BytesIO(b">seq1\nMKVLAAGIVGLSTAAQLAKR\n>seq2\nMKVLGAGIVGLSTAAQLAKR\n")
    with pytest.raises(ValueError, match="nucleotide"):
        hmmer_build(msa_file, name="p", window_length=200)


def test_hmmer_build_window_length_and_beta_mutually_exclusive(shared_datadir):
    with pytest.raises(ValueError, match="Only one of window_length and window_beta"):
        hmmer_build(str(shared_datadir / "dna_msa_1.afa"), name="d", window_length=200, window_beta=1e-3)


def test_hmmer_build_ambiguous_alphabet_error_mentions_flag():
    # Too few columns for pyhmmer to guess the alphabet.
    with pytest.raises(ValueError, match="--alphabet"):
        hmmer_build(BytesIO(b">seq1\nAC\n>seq2\nAC\n"), name="x")


def test_hmmer_build_empty_input_raises():
    # MSAFile segfaults the interpreter on an empty stream under pyhmmer 0.12, so streams
    # are read from a temporary copy, and an empty one is refused before pyhmmer sees it.
    with pytest.raises(ValueError, match="empty"):
        hmmer_build(BytesIO(b""), name="x")


def test_hmmer_build_unnamed_msa_raises():
    with pytest.raises(ValueError, match="unnamed"):
        hmmer_build(BytesIO(b">seq1\nACGTACGTACGTACGTACGTAC\n>seq2\nACGTACGTTCGTACGTACGTAC\n"))


def test_hmmer_build_gzip_output(msa_file, tmp_path):
    from domainator.seqio import detect_compression
    from domainator.hmmio import open_hmm_file
    out = tmp_path / "out.hmm.gz"
    main(["--name", "test_profile", "--input", msa_file, "-o", str(out)])
    assert detect_compression(out) == "gzip"
    with open_hmm_file(out) as handle:
        profiles = list(handle)
    assert [h.name for h in profiles] == ["test_profile"]


def test_hmmer_build_rejects_bgzf_output(msa_file, tmp_path):
    with pytest.raises(ValueError, match="BGZF"):
        main(["--name", "test_profile", "--input", msa_file, "-o", str(tmp_path / "out.hmm.bgz")])


# --- MSA formats -----------------------------------------------------------
#
# msa_formats/FeSOD_20.* are FeSOD_20.afa written by pyhmmer's TextMSA.write in each
# format (the A2M copy with an RF line marking the columns that are at least half
# residues, since A2M written without one does not read back). The small .txt files are
# hand-written cases for the guess from content: classic PHYLIP (names holding spaces,
# glued to the sequence), a PHYLIP name field wider than 10, SELEX with spaces as gaps,
# Clustal with residue counts, and a MUSCLE header.

@pytest.mark.parametrize("fixture", [
    "FeSOD_20.sto", "FeSOD_20.aln", "FeSOD_20_clustallike.txt", "FeSOD_20.phy", "FeSOD_20.phys",
    "FeSOD_20.slx", "FeSOD_20.pb", "FeSOD_20.a2m", "phylip_interleaved.txt", "phylip_sequential.txt",
    "phylip_wide_names.txt", "selex_space_gaps.txt", "clustal_residue_counts.txt", "muscle.txt",
])
def test_hmmer_build_msa_formats(shared_datadir, tmp_path, fixture):
    out = tmp_path / "out.hmm"
    main(["--name", "f", "--input", str(shared_datadir / "msa_formats" / fixture), "-o", str(out)])
    assert "NAME  f" in out.read_text()


def _profile_body(hmm):
    handle = BytesIO()
    hmm.write(handle)
    return [l for l in handle.getvalue().decode().splitlines() if not l.startswith(("DATE", "COM"))]


@pytest.mark.parametrize("fixture", [
    "FeSOD_20.sto", "FeSOD_20.aln", "FeSOD_20_clustallike.txt", "FeSOD_20.phy", "FeSOD_20.phys", "FeSOD_20.slx",
])
def test_hmmer_build_formats_of_one_alignment_agree(shared_datadir, fixture):
    expected = _profile_body(hmmer_build(str(shared_datadir / "FeSOD_20.afa"), name="f"))
    assert _profile_body(hmmer_build(str(shared_datadir / "msa_formats" / fixture), name="f")) == expected


@pytest.mark.parametrize("content", [b"\n \n", b"hello world foo\nbar\n"])
def test_hmmer_build_unrecognized_stream_raises(content):
    # pyhmmer 0.12's MSAFile segfaults the interpreter on a stream whose format it
    # cannot guess, so hmmer_build reads streams from a temporary copy.
    with pytest.raises(ValueError, match="format of the input MSA"):
        hmmer_build(BytesIO(content), name="x")


def test_hmmer_build_selex_stream(shared_datadir):
    # Read through MSAFile directly, a SELEX stream fails with "illegal residue(s)" once
    # its alphabet has been guessed.
    data = (shared_datadir / "msa_formats" / "FeSOD_20.slx").read_bytes()
    assert _profile_body(hmmer_build(BytesIO(data), name="f")) == _profile_body(
        hmmer_build(str(shared_datadir / "FeSOD_20.afa"), name="f"))


def test_hmmer_build_a2m_needs_its_suffix(shared_datadir):
    # A2M cannot be told from aligned FASTA by content: as a stream it is read as aligned
    # FASTA, whose rows must all be the same length.
    path = shared_datadir / "msa_formats" / "FeSOD_20.a2m"
    with pytest.raises(ValueError, match="alen"):
        hmmer_build(BytesIO(path.read_bytes()), name="f")
    assert "RF    yes" in "\n".join(_profile_body(hmmer_build(str(path), name="f")))
